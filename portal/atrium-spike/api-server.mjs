import nodemailer from 'nodemailer';
import assert from 'node:assert/strict';
import {existsSync,writeFileSync,renameSync,readFileSync} from 'node:fs';
import {digest} from '../../gateway/src/store.mjs';
import {createApiRuntime} from './api-runtime.mjs';
for(const path of ['/credentials','/migration-credentials','/worker-credentials','/gateway-credentials','/db-tls','/provider-runtime','/worker-config','/runtime'])assert(!existsSync(path),'Privileged fixture mount is forbidden');
assert.equal(new URL(process.env.DATABASE_URL).username,'gc_app');
const write=(name,contents)=>{writeFileSync('/api-evidence/'+name+'.tmp',contents);renameSync('/api-evidence/'+name+'.tmp','/api-evidence/'+name);};
const counts={storage:0,stripe:0,notifications:0};
write('side-effects.json',JSON.stringify(counts));
const sideEffects=new Proxy(counts,{set(target,key,value){target[key]=value;write('side-effects.json',JSON.stringify(target));return true;}});
const browserMode=process.env.PORTAL_BROWSER==='1';
const mail=nodemailer.createTransport({host:'mail',port:1025,secure:false,ignoreTLS:true});
const runtime=createApiRuntime({authSecret:readFileSync('/auth-credentials/secret','utf8').trim(),databaseUrl:process.env.DATABASE_URL,browserMode,origin:browserMode?'https://portal.growthcast.test:8444':'http://localhost:3001',sideEffects,onMail:async(email,html)=>{
  assert(/^[a-zA-Z0-9._+-]+@(example\.test|growthcast\.invalid)$/.test(email),'Synthetic recipient required');
  await mail.sendMail({from:'portal@growthcast.invalid',to:email,subject:'Local verification',html});
  write('mail-'+digest(email)+'.html',html);
}});
await runtime.start();
assert.equal((await runtime.db.$queryRawUnsafe('SELECT current_user')).at(0).current_user,'gc_app');
assert.equal((await runtime.db.$queryRawUnsafe('SELECT ssl FROM pg_stat_ssl WHERE pid=pg_backend_pid()')).at(0).ssl,true);
for(const sql of ['CREATE TABLE public.api_escape(id integer)','DELETE FROM sealed_artifacts','SET ROLE gc_migrate','SET ROLE postgres'])await assert.rejects(()=>runtime.store.pool.query(sql));
write('ready.json',JSON.stringify({databaseRole:'gc_app',tls:true,privilegedCredentialsAbsent:true}));
console.log('Isolated API ready with restricted database identity, verified TLS and no privileged fixture mounts.');
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,async()=>{await runtime.close();process.exit(0);});
