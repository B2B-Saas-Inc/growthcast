import assert from 'node:assert/strict';
import {StripeService} from '/upstream/apps/api/dist/billing/stripe.service.js';
import {ConnectWebhookController} from '/upstream/apps/api/dist/payments/connect-webhook.controller.js';
const sdk=new StripeService({get:(_key,fallback)=>fallback});
const secret='whsec_growthcast_synthetic_verification',payload=JSON.stringify({id:'evt_synthetic',type:'growthcast.acceptance.noop',data:{object:{}}});
const signature=await sdk.stripe.webhooks.generateTestHeaderStringAsync({payload,secret});
let calls=0;const payments={getOrgWebhookSecret:async()=>secret,getConnectWebhookSecret:()=>secret,handleWebhookEvent:async()=>{calls++}};
const controller=new ConnectWebhookController(payments,sdk);controller.logger={error:()=>{}};
const req={headers:{'stripe-signature':signature},rawBody:Buffer.from(payload)};
assert.deepEqual(await controller.handleDirectWebhook('synthetic-org',req),{received:true});
assert.deepEqual(await controller.handleConnectWebhook(req),{received:true});
await assert.rejects(()=>controller.handleDirectWebhook('synthetic-org',{...req,rawBody:Buffer.from(payload+'tampered')}));
await assert.rejects(()=>controller.handleDirectWebhook('synthetic-org',{...req,headers:{'stripe-signature':'t=1,v1=bad'}}));
assert.equal(calls,2);console.log('Actual Bun/Stripe controller verifies direct and Connect signatures asynchronously and rejects tampering.');
